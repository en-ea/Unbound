import { readFileSync } from 'node:fs';
import { createVillage, run, YEAR } from '../../../../../tools-src/studio/village-reference/village.mjs';
import { book, extractTales } from '../../../../../tools-src/studio/village-reference/tales.mjs';

const books = [
  [1000, 'Wenbrook', 'wenbrook-1000-years.md'],
  [8919, 'Harrowmere', 'harrowmere-1000-years.md'],
  [16838, 'Ashcombe', 'ashcombe-1000-years.md'],
];
let failed = false;
for (const [seed, name, filename] of books) {
  const years = 1000, perCentury = 3;
  const stormPlan = [];
  for (let y = 50; y < years; y += 97) stormPlan.push({ day: y * YEAR + 20, household: (seed + y) % 6, days: 90 });
  const V = createVillage(seed, { stormPlan, name });
  run(V, years * YEAR);
  const expectedBook = book(V, years, perCentury);
  const front = `---\ntitle: "The Tales of ${V.name}, years 1-${years}"\ncreated: 2026-09-29\ntype: generated\nvoice: agent-draft\nauthor: generated by tools-src/studio/village-reference/book.mjs (seed ${seed}); sentence patterns by Claude (claude-opus-5-5)\nstatus: a demonstration of the village simulation's range, not game text. Nothing here is decided until Enea says so\nnext_step: Enea and Hilmi read one book and say which tales feel like Unbound and which do not; that tunes the rules\n---\n\n`;
  const actual = readFileSync(new URL(`../../../tales/${filename}`, import.meta.url), 'utf8');
  const exact = actual === front + expectedBook.markdown + '\n';
  const tales = extractTales(V, perCentury);
  let invalidLinks = 0, missingCauses = 0, missingCues = 0;
  for (const tale of tales) {
    const root = V.events[tale.root];
    if (!root.causes.length && !root.data.motive) missingCauses++;
    if (!root.cue) missingCues++;
    for (const id of tale.ids) for (const cause of V.events[id].causes)
      if (!Number.isInteger(cause) || cause < 0 || cause >= id) invalidLinks++;
  }
  const result = { seed, name, years, perCentury, storms: stormPlan.length, tales: tales.length,
    exact, invalidLinks, missingCauses, missingCues };
  console.log(JSON.stringify(result));
  if (!exact || invalidLinks || missingCauses || missingCues) failed = true;
}
if (failed) process.exitCode = 1;
