import { readFileSync } from 'node:fs';
import { createVillage, run, YEAR } from '../../../../../tools-src/studio/village-reference/village.mjs';
import { book, extractTales } from '../../../../../tools-src/studio/village-reference/tales.mjs';

const inputs = [
  [1000, 'Wenbrook', 'wenbrook-1000-years.md'],
  [8919, 'Harrowmere', 'harrowmere-1000-years.md'],
  [16838, 'Ashcombe', 'ashcombe-1000-years.md'],
];
let failed = false;
for (const [seed, name, file] of inputs) {
  const years = 1000, perCentury = 3;
  const stormPlan = [];
  for (let y = 50; y < years; y += 97) stormPlan.push({ day: y * YEAR + 20, household: (seed + y) % 6, days: 90 });
  const V = createVillage(seed, { stormPlan, name });
  run(V, years * YEAR);
  const generated = book(V, years, perCentury);
  const preserved = readFileSync(new URL(`../../../tales/${file}`, import.meta.url), 'utf8');
  const marker = `# The Tales of ${name}, years 1-${years}`;
  const start = preserved.indexOf(marker);
  const actualBody = start >= 0 ? preserved.slice(start).trimEnd() : '';
  const expectedBody = generated.markdown.trimEnd();
  const bodyMatches = actualBody === expectedBody;
  let firstDifference = -1;
  if (!bodyMatches) {
    firstDifference = 0;
    while (firstDifference < actualBody.length && firstDifference < expectedBody.length && actualBody[firstDifference] === expectedBody[firstDifference]) firstDifference++;
  }
  const labelMatches = preserved.includes(`author: generated by tools-src/studio/village-reference/book.mjs (seed ${seed})`)
    && preserved.includes('type: generated') && preserved.includes('voice: agent-draft')
    && preserved.includes('status: a demonstration of the village simulation\'s range, not game text. Nothing here is decided until Enea says so');
  const tales = extractTales(V, perCentury);
  const invalidLinks = tales.flatMap(t => t.ids.flatMap(id => V.events[id].causes.filter(c => !Number.isInteger(c) || c < 0 || c >= id)));
  const uncausedRoots = tales.filter(t => !V.events[t.root].causes.length && !V.events[t.root].data.motive).map(t => t.root);
  const uncued = tales.filter(t => !V.events[t.root].cue).map(t => t.root);
  const endings = V.stats.outcomes;
  const denominator = V.cases.length;
  const sorted = Object.entries(endings).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
  const maximum = sorted[0] ?? ['none', 0];
  const under40 = denominator > 0 && maximum[1] / denominator <= 0.4;
  const output = { seed, name, years, perCentury, storms: stormPlan.length, tales: tales.length,
    bodyMatches, firstDifference,
    preservedAtDifference: firstDifference < 0 ? '' : actualBody.slice(firstDifference, firstDifference + 100),
    generatedAtDifference: firstDifference < 0 ? '' : expectedBody.slice(firstDifference, firstDifference + 100),
    labelMatches, invalidLinks: invalidLinks.length, uncausedRoots, uncued,
    cases: denominator, endingCounts: Object.fromEntries(sorted), classified: sorted.reduce((n, [, count]) => n + count, 0),
    maximum: { ending: maximum[0], count: maximum[1], share: +(100 * maximum[1] / denominator).toFixed(2) }, under40 };
  console.log(JSON.stringify(output));
  if (!bodyMatches || !labelMatches || invalidLinks.length || uncausedRoots.length || uncued.length || !under40) failed = true;
}
if (failed) process.exitCode = 1;
